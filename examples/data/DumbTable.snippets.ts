// Отдельный файл, потому что подсветка считается НА СБОРКЕ: плагин
// playground/snippets.ts выполняет этот модуль в Node, гонит каждую строку
// через Shiki и подменяет экспорт на { code, html }. Отсюда два требования: в
// файле только строки и ни одного импорта.
export default {
  install: 'pnpm add @solid-dumb-kit/table',

  basic: [
    "import { DumbTable, type DumbColumn } from '@solid-dumb-kit/table'",
    '',
    'const columns: DumbColumn<Row>[] = [',
    "  { key: 'name', label: 'Товар', sortable: true },",
    '  {',
    "    key: 'price',",
    "    label: 'Цена',",
    "    align: 'right',",
    '    sortable: true,',
    '    render: (row) => fmtPrice(row.price),',
    '  },',
    '  {',
    "    key: 'actions',",
    "    label: '',",
    "    width: '48px',",
    '    stopClick: true, // клик по кнопке не пойдёт в onRowClick',
    '    render: (row) => <button class="btn btn-xs">⋯</button>,',
    '  },',
    ']',
    '',
    '<DumbTable rows={rows()} columns={columns} onRowClick={(row) => open(row)} />',
  ].join('\n'),

  sort: [
    '// Без onSort таблица сортирует сама, на клиенте.',
    '<DumbTable rows={rows()} columns={columns} viewTransition />',
    '',
    '// Есть onSort — сортирует СЕРВЕР: таблица только рисует стрелку и зовёт вас.',
    '// Третий клик по колонке сбрасывает сортировку — тогда придёт (null, null).',
    '<DumbTable',
    '  rows={rows()}',
    '  columns={columns}',
    '  sort={sort()}',
    '  order={order()}',
    '  onSort={(key, dir) => {',
    '    setSort(key)',
    '    setOrder(dir)',
    '    reload()',
    '  }}',
    '  // все колонки начинают с asc: по умолчанию числовые начинают с desc',
    '  sortDescFirst={false}',
    '  noSortRemoval',
    '/>',
  ].join('\n'),

  drag: [
    '// Перетаскивание строк. Индексы приходят в ТЕКУЩЕМ показанном порядке,',
    '// поэтому при пагинации не забудьте смещение страницы.',
    '<DumbTable',
    '  rows={pageRows()}',
    '  columns={columns}',
    '  rowId={(row) => row.id}',
    '  onReorder={(from, to) => {',
    '    const off = (page() - 1) * pageSize()',
    '    move(off + from, off + to)',
    '  }}',
    '  // handle={false} — ручки нет, строка тянется целиком; тогда нужен порог,',
    '  // иначе клик по строке и начало драга неотличимы',
    '  handle={<span class="icon-[solar--hamburger-menu-linear]" />}',
    '  dragThreshold={4}',
    '/>',
    '',
    '// Пока активна сортировка, драг выключается сам: from → to описывают',
    '// показанный порядок, который при сортировке не совпадает с порядком данных.',
  ].join('\n'),

  pagination: [
    '// Таблица НЕ пагинирует: строки режет потребитель, DumbPagination только',
    '// рисует пагинатор.',
    "import { DumbPagination } from '@solid-dumb-kit/table'",
    '',
    'const shown = () => rows().slice((page() - 1) * size(), page() * size())',
    '',
    '<DumbTable rows={shown()} columns={columns} loading={busy()} empty={<Empty />} />',
    '',
    '<DumbPagination',
    '  page={page()}',
    '  total={rows().length}',
    '  pageSize={size()}',
    '  onPageChange={setPage}',
    '  pageSizes={[10, 25, 50]}',
    '  onPageSizeChange={setSize}',
    '/>',
  ].join('\n'),

  gotcha: [
    '// Грабли TanStack, о которые бьются все:',
    '//',
    '// 1. Колонке ОБЯЗАТЕЛЕН accessor — у нас это key или value. Без него',
    '//    TanStack считает колонку display-колонкой, getCanSort() всегда false,',
    "//    и сортировка молча выключается, даже когда sortable: true.",
    '{',
    "  key: 'total',",
    "  label: 'Сумма',",
    '  sortable: true,',
    '  value: (row) => row.price * row.qty, // значение для сортировки',
    '  render: (row) => fmtPrice(row.price * row.qty),',
    '}',
    '',
    '// 2. Первый клик: текстовые колонки начинают с asc, ЧИСЛОВЫЕ с desc —',
    '//    это дефолт TanStack. Перебивается пропом sortDescFirst.',
    '//',
    '// 3. При onReorder слева добавляется колонка с ручкой, и индексы <th>',
    '//    сдвигаются на единицу — легко ошибиться в тестах.',
  ].join('\n'),
}

