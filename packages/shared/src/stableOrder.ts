// Неизменный порядок рендера — чтобы перестановка не двигала DOM.
//
// Компоненты кита показывают порядок через CSS `order`, а сам список рендерят
// так, чтобы перестановки его не задевали: тогда `<For>` при них не делает
// ничего, ни одного перемещения узла за жест.
//
// Первым подходом была сортировка по id — она стабильна, но читать разметку
// после неё невозможно: `r10` встаёт раньше `r2`, а сотня блоков ложится в
// порядке, который ни с чем на экране не совпадает. Стабильный порядок не обязан
// быть отсортированным — достаточно, чтобы он не зависел от перестановок.
//
// Поэтому запоминаем, кого увидели первым, и держимся этого. На старте выходит
// ровно тот порядок, в котором элементы пришли, — то есть разметка совпадает с
// исходным списком. Новый элемент получает следующий номер и встаёт в конец
// разметки, где бы он ни показывался.
//
// Оговорка про доступность: экранный диктор и Tab идут по разметке, а не по
// `order`. После перестановок озвучиваемый порядок разойдётся с видимым — это
// цена подхода, и она известна (об этом же предупреждает спецификация flexbox).
// Для списков, которые пользователь сам и переставляет, это приемлемо; для
// текста, который читают подряд, — нет.

export type StableOrder<T> = {
  /**
   * Отсортировать по порядку появления; новые получают номер тут же, за
   * исчезнувшими прибирается. Отдавать сюда надо ВЕСЬ список: по подмножеству
   * уборка выбросит тех, кого в нём просто не было, и при следующем вызове они
   * получат новые номера — порядок поедет на ровном месте.
   */
  sort: (items: Array<T>) => Array<T>
  /** номер элемента — чтобы отсортировать подмножество, не трогая карту */
  rank: (item: T) => number
}

/**
 * @param id как достать стабильный id элемента
 */
export function createStableOrder<T>(id: (item: T) => string): StableOrder<T> {
  const seen = new Map<string, number>()
  let next = 0

  return {
    sort(items) {
      const live = new Set<string>()
      for (const it of items) {
        const key = id(it)
        live.add(key)
        if (!seen.has(key)) seen.set(key, next++)
      }
      // за исчезнувшими прибираем: иначе на длинной жизни списка с текучим
      // составом карта растёт без границы
      if (seen.size > live.size) {
        for (const key of seen.keys()) if (!live.has(key)) seen.delete(key)
      }
      return items.slice().sort((a, b) => seen.get(id(a))! - seen.get(id(b))!)
    },
    rank(item) {
      return seen.get(id(item)) ?? Number.MAX_SAFE_INTEGER
    },
  }
}
