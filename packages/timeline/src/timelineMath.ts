// Тип отрезка и две функции по календарным суткам.
//
// Раньше здесь лежала вся геометрия шахматки: место полосы, клетка под точкой,
// пересечения, поиск свободного. Всё это переехало в `scale.ts` и было отсюда
// УДАЛЕНО, а не оставлено «на всякий случай», — и вот почему.
//
// Шкала знает то, чего здешние функции знать не могли: рабочее окно дня (ночь
// вырезана), час заезда и выезда, зазор на уборку. Их ответы расходились с
// поведением компонента: `spansOverlap` говорил «свободно» там, где сетка
// показывает конфликт, а `spanBox` рисовал сутки целиком там, где полоса идёт
// с 16:00 до 12:00. Две правды в публичном API хуже одной: по второй пишут
// проверки на сервере, и они начинают расходиться с тем, что видно на экране.
//
// Осталось только то, что от шкалы не зависит.

/** `YYYY-MM-DD` — строка, а не `Date`: часовые пояса сдвигают сутки */
export type Day = string

/** Отрезок на шахматке. Моменты — `YYYY-MM-DD` или `YYYY-MM-DDTHH:mm`. */
export type Span = {
  id: string
  /** в какой строке */
  row: string
  from: string
  /** конец: у суточной брони это день выезда */
  to: string
}

import { Temporal } from './temporal'

const plain = (day: Day) => Temporal.PlainDate.from(day.slice(0, 10))

/**
 * Сколько КАЛЕНДАРНЫХ суток между датами. Время игнорируется намеренно: это
 * «сколько ночей», а не «сколько часов».
 *
 * `PlainDate` не знает часовых поясов — значит переход на летнее время и
 * прочая зонная механика тут не существуют в принципе, а не «не мешают».
 */
export const daysApart = (a: Day, b: Day): number =>
  plain(a).until(plain(b), { largestUnit: 'day' }).days

/** сдвинуть дату на N суток */
export const shiftDay = (day: Day, n: number): Day => plain(day).add({ days: n }).toString()
